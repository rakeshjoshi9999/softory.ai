export interface TemplateVars {
  name: string;
  scope: string;
  directory: string;
  rootRelative: string;
}

const json = (value: unknown) => JSON.stringify(value, null, 2) + '\n';

/** Thin Helm chart: every template comes from the factory-lib library chart. */
function chartFiles(v: TemplateVars): Record<string, string> {
  return {
    'chart/Chart.yaml': `apiVersion: v2
name: ${v.name}
description: Thin chart for ${v.name}; templates come from factory-lib
type: application
version: 0.1.0
appVersion: "0.0.0"
dependencies:
  - name: factory-lib
    version: 0.1.0
    repository: file://${v.rootRelative}../deploy/charts/factory-lib
`,
    'chart/templates/workload.yaml': `{{- include "factory-lib.service" . }}
`,
    'chart/values.yaml': `replicaCount: 1
image:
  repository: registry.local/factory/${v.name}
  tag: latest
  pullPolicy: IfNotPresent
resources:
  requests: { cpu: 50m, memory: 64Mi }
  limits: { cpu: 500m, memory: 256Mi }
port: 3000
healthPath: /health
`,
  };
}

export function renderTemplates(v: TemplateVars): Record<string, string> {
  return {
    ...chartFiles(v),
    'package.json': json({ name: `@factory/${v.name}`, version: '0.0.0', private: true }),
    'project.json': json({
      name: v.name,
      $schema: `${v.rootRelative}node_modules/nx/schemas/project-schema.json`,
      sourceRoot: `${v.directory}/src`,
      projectType: 'application',
      tags: ['type:product', `scope:${v.scope}`],
      targets: {
        build: {
          executor: 'nx:run-commands',
          outputs: [`{workspaceRoot}/dist/${v.directory}`],
          options: { command: `tsc -p ${v.directory}/tsconfig.app.json`, cwd: '{workspaceRoot}' },
        },
        test: {
          executor: 'nx:run-commands',
          options: { command: `vitest run --root . ${v.directory}`, cwd: '{workspaceRoot}' },
        },
      },
    }),
    // tsconfig.json carries the decorator flags so vite/esbuild (vitest) compiles Nest decorators too
    'tsconfig.json': json({
      extends: `${v.rootRelative}tsconfig.base.json`,
      compilerOptions: {
        experimentalDecorators: true,
        emitDecoratorMetadata: true,
        module: 'commonjs',
        moduleResolution: 'node10',
        types: ['node'],
      },
      include: ['src/**/*.ts'],
    }),
    'tsconfig.app.json': json({
      extends: './tsconfig.json',
      compilerOptions: { outDir: `${v.rootRelative}dist/${v.directory}`, rootDir: 'src' },
      include: ['src/**/*.ts'],
      exclude: ['src/**/*.spec.ts'],
    }),
    'README.md': `# ${v.name}

NestJS service generated by the \`nestjs-service\` recipe.

- \`GET /health\` returns \`{ "status": "ok" }\`
- Configuration is validated at startup (\`src/config/config.ts\`); see the variables below.
- OpenTelemetry tracing starts first in \`src/main.ts\` and exports over OTLP/HTTP.
- Hand-written code goes in \`src/ext/\`. Emitted packages live in \`generated/\` folders and are never edited by hand.

| Variable | Default | Meaning |
| --- | --- | --- |
| \`PORT\` | \`3000\` | HTTP port |
| \`SERVICE_NAME\` | \`${v.name}\` | Name reported to OpenTelemetry |
| \`OTEL_EXPORTER_OTLP_ENDPOINT\` | unset | Set to enable trace export |
`,
    'src/main.ts': `import 'reflect-metadata';
import { startTelemetry } from './telemetry';
import { loadConfig } from './config/config';

async function bootstrap(): Promise<void> {
  const config = loadConfig(process.env);
  await startTelemetry(config);
  const { NestFactory } = await import('@nestjs/core');
  const { AppModule } = await import('./app.module');
  const app = await NestFactory.create(AppModule);
  await app.listen(config.port);
}

void bootstrap();
`,
    'src/app.module.ts': `import { Module } from '@nestjs/common';
import { HealthController } from './health/health.controller';
import { ExtModule } from './ext';

@Module({
  imports: [ExtModule],
  controllers: [HealthController],
})
export class AppModule {}
`,
    'src/health/health.controller.ts': `import { Controller, Get } from '@nestjs/common';

@Controller('health')
export class HealthController {
  @Get()
  check(): { status: 'ok' } {
    return { status: 'ok' };
  }
}
`,
    'src/health/health.controller.spec.ts': `import { describe, expect, it } from 'vitest';
import { HealthController } from './health.controller';

describe('HealthController', () => {
  it('reports ok', () => {
    expect(new HealthController().check()).toEqual({ status: 'ok' });
  });
});
`,
    'src/config/config.ts': `export interface Config {
  port: number;
  serviceName: string;
  otlpEndpoint?: string;
}

export function loadConfig(env: Record<string, string | undefined>): Config {
  const errors: string[] = [];
  const rawPort = env['PORT'] ?? '3000';
  const port = Number(rawPort);
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    errors.push(\`PORT must be an integer between 1 and 65535, got "\${rawPort}"\`);
  }
  const serviceName = env['SERVICE_NAME'] ?? '${v.name}';
  if (serviceName.trim() === '') {
    errors.push('SERVICE_NAME must not be empty');
  }
  const otlpEndpoint = env['OTEL_EXPORTER_OTLP_ENDPOINT'];
  if (otlpEndpoint !== undefined && !URL.canParse(otlpEndpoint)) {
    errors.push(\`OTEL_EXPORTER_OTLP_ENDPOINT must be a URL, got "\${otlpEndpoint}"\`);
  }
  if (errors.length > 0) {
    throw new Error(\`Invalid configuration:\\n- \${errors.join('\\n- ')}\`);
  }
  return { port, serviceName, ...(otlpEndpoint !== undefined && { otlpEndpoint }) };
}
`,
    'src/config/config.spec.ts': `import { describe, expect, it } from 'vitest';
import { loadConfig } from './config';

describe('loadConfig', () => {
  it('applies defaults', () => {
    expect(loadConfig({})).toEqual({ port: 3000, serviceName: '${v.name}' });
  });

  it('reads overrides', () => {
    expect(loadConfig({ PORT: '8080', OTEL_EXPORTER_OTLP_ENDPOINT: 'http://otel:4318' })).toMatchObject({
      port: 8080,
      otlpEndpoint: 'http://otel:4318',
    });
  });

  it('rejects invalid values with every problem listed', () => {
    expect(() => loadConfig({ PORT: 'abc', OTEL_EXPORTER_OTLP_ENDPOINT: 'nope' })).toThrow(/PORT[\\s\\S]*OTEL_EXPORTER/);
  });
});
`,
    'src/telemetry.ts': `import type { Config } from './config/config';

/** Starts OpenTelemetry tracing. Exports over OTLP/HTTP only when OTEL_EXPORTER_OTLP_ENDPOINT is set. */
export async function startTelemetry(config: Config): Promise<void> {
  if (config.otlpEndpoint === undefined) {
    return;
  }
  const { NodeSDK } = await import('@opentelemetry/sdk-node');
  const { OTLPTraceExporter } = await import('@opentelemetry/exporter-trace-otlp-http');
  const sdk = new NodeSDK({
    serviceName: config.serviceName,
    traceExporter: new OTLPTraceExporter({ url: \`\${config.otlpEndpoint}/v1/traces\` }),
  });
  sdk.start();
  process.once('SIGTERM', () => void sdk.shutdown());
}
`,
    'src/ext/index.ts': `import { Module } from '@nestjs/common';

/** Hand-written code lives in src/ext/. Add providers and controllers here. */
@Module({})
export class ExtModule {}
`,
  };
}
