export interface TemplateVars {
  name: string;
  scope: string;
  directory: string;
  rootRelative: string;
}

const json = (value: unknown) => JSON.stringify(value, null, 2) + '\n';

export function renderTemplates(v: TemplateVars): Record<string, string> {
  const selector = `app-${v.name}`;
  return {
    'package.json': json({ name: `@factory/${v.name}`, version: '0.0.0', private: true }),
    'project.json': json({
      name: v.name,
      $schema: `${v.rootRelative}node_modules/nx/schemas/project-schema.json`,
      sourceRoot: `${v.directory}/src`,
      projectType: 'application',
      tags: ['type:product', `scope:${v.scope}`],
      targets: {
        build: {
          executor: 'nx:run-commands',
          outputs: [`{workspaceRoot}/dist/${v.directory}`],
          options: { command: `ngc -p ${v.directory}/tsconfig.app.json`, cwd: '{workspaceRoot}' },
        },
        test: {
          executor: 'nx:run-commands',
          options: { command: `vitest run --root . ${v.directory}`, cwd: '{workspaceRoot}' },
        },
      },
    }),
    // tsconfig.json carries the decorator flag so vite/esbuild (vitest) compiles Angular decorators too
    'tsconfig.json': json({
      extends: `${v.rootRelative}tsconfig.base.json`,
      compilerOptions: {
        experimentalDecorators: true,
        module: 'esnext',
        moduleResolution: 'bundler',
        lib: ['es2022', 'dom'],
        types: [],
      },
      include: ['src/**/*.ts'],
    }),
    'tsconfig.app.json': json({
      extends: './tsconfig.json',
      compilerOptions: { outDir: `${v.rootRelative}dist/${v.directory}`, rootDir: 'src' },
      include: ['src/**/*.ts'],
      exclude: ['src/**/*.spec.ts'],
      angularCompilerOptions: { strictTemplates: true, strictInjectionParameters: true },
    }),
    'federation.config.js': `/* eslint-disable @typescript-eslint/no-require-imports -- native-federation reads this file as CommonJS */
const { withNativeFederation, shareAll } = require('@angular-architects/native-federation/config');

module.exports = withNativeFederation({
  name: '${v.name}',
  exposes: {
    './routes': './src/app/remote.routes.ts',
  },
  shared: {
    ...shareAll({ singleton: true, strictVersion: true, requiredVersion: 'auto' }),
  },
  skip: ['rxjs/ajax', 'rxjs/fetch', 'rxjs/testing', 'rxjs/webSocket'],
});
`,
    'README.md': `# ${v.name}

Angular remote generated by the \`angular-remote\` recipe.

- Standalone components, signals, lazy routing (\`src/app/app.routes.ts\`).
- Exposed through Native Federation as \`./routes\` (\`federation.config.js\`); a shell loads \`remoteEntry.json\` and mounts \`remote.routes.ts\`.
- Hand-written code goes in \`src/ext/\` (routes added to \`extRoutes\` appear under \`/ext\`). Emitted packages live in \`generated/\` folders and are never edited by hand.
`,
    'src/index.html': `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <title>${v.name}</title>
    <base href="/" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
  </head>
  <body>
    <${selector}></${selector}>
  </body>
</html>
`,
    'src/main.ts': `import { initFederation } from '@angular-architects/native-federation';

initFederation('federation.manifest.json')
  .catch((err: unknown) => console.error(err))
  .then(() => import('./bootstrap'))
  .catch((err: unknown) => console.error(err));
`,
    'src/bootstrap.ts': `import { bootstrapApplication } from '@angular/platform-browser';
import { appConfig } from './app/app.config';
import { AppComponent } from './app/app.component';

bootstrapApplication(AppComponent, appConfig).catch((err: unknown) => console.error(err));
`,
    'src/app/app.config.ts': `import type { ApplicationConfig } from '@angular/core';
import { provideRouter } from '@angular/router';
import { routes } from './app.routes';

export const appConfig: ApplicationConfig = {
  providers: [provideRouter(routes)],
};
`,
    'src/app/app.component.ts': `import { Component } from '@angular/core';
import { RouterOutlet } from '@angular/router';

@Component({
  selector: '${selector}',
  imports: [RouterOutlet],
  template: '<router-outlet />',
})
export class AppComponent {}
`,
    'src/app/app.routes.ts': `import type { Routes } from '@angular/router';
import { remoteRoutes } from './remote.routes';

/** Standalone (local dev) routes: the same routes the shell mounts. */
export const routes: Routes = remoteRoutes;
`,
    'src/app/remote.routes.ts': `import type { Routes } from '@angular/router';
import { extRoutes } from '../ext';

/** Exposed to the shell through Native Federation as './routes'. */
export const remoteRoutes: Routes = [
  { path: '', pathMatch: 'full', loadComponent: () => import('./home.component').then((m) => m.HomeComponent) },
  { path: 'ext', children: extRoutes },
];
`,
    'src/app/home.component.ts': `import { Component, signal } from '@angular/core';

@Component({
  selector: '${selector}-home',
  template: '<h1>{{ title() }}</h1>',
})
export class HomeComponent {
  readonly title = signal('${v.name}');
}
`,
    'src/app/remote.routes.spec.ts': `import { describe, expect, it } from 'vitest';
import { remoteRoutes } from './remote.routes';

describe('remoteRoutes', () => {
  it('has a lazy home route', () => {
    const home = remoteRoutes.find((r) => r.path === '');
    expect(home?.loadComponent).toBeTypeOf('function');
  });

  it('mounts hand-written routes from src/ext under /ext', () => {
    expect(remoteRoutes.some((r) => r.path === 'ext')).toBe(true);
  });
});
`,
    'src/ext/index.ts': `import type { Routes } from '@angular/router';

/** Hand-written code lives in src/ext/. Add routes here; they are mounted under /ext. */
export const extRoutes: Routes = [];
`,
  };
}
