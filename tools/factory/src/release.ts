import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';
import { attest } from './attest.js';
import { emitterRef, gitCommit, provenanceFor, writeProvenance } from './provenance.js';

export const DEFAULT_REGISTRY = 'http://localhost:4873/';

export interface ReleasePackage {
  name: string;
  dir: string;
  /** Generated emitter output this package ships. */
  source: string;
  /** Barrel written into the package when the emitter does not produce one. */
  barrel?: string[];
  /** Emitter project that produced `source`. */
  emitter: string;
}

export function packagesFor(material: string, root = '.'): ReleasePackage[] {
  const base = join(root, 'materials', material);
  return [
    {
      name: `@factory/${material}-angular`,
      dir: join(base, 'packages', 'angular'),
      source: join(base, 'generated', 'angular-client'),
      barrel: ['./models/index', './orders/orders.service'],
      emitter: 'ts-angular-client',
    },
    {
      name: `@factory/${material}-nest`,
      dir: join(base, 'packages', 'nest'),
      source: join(base, 'generated', 'nest-server'),
      emitter: 'nest-server',
    },
  ];
}

/** Copies emitter output into the package's (gitignored) src folder. */
export function stage(pkg: ReleasePackage): void {
  if (!existsSync(pkg.source)) throw new Error(`${pkg.source} missing: run the material's emit targets first`);
  const out = join(pkg.dir, 'src');
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  cpSync(pkg.source, out, { recursive: true });
  if (pkg.barrel) {
    writeFileSync(join(out, 'index.ts'), `// Generated by release staging. Do not edit.\n${pkg.barrel.map((p) => `export * from '${p}';`).join('\n')}\n`);
  }
}

export function pendingChangesets(root = '.'): boolean {
  const dir = join(root, '.changeset');
  return existsSync(dir) && readdirSync(dir).some((f) => f.endsWith('.md') && f !== 'README.md');
}

export function readVersion(pkg: ReleasePackage): string {
  return JSON.parse(readFileSync(join(pkg.dir, 'package.json'), 'utf8')).version;
}

function npmEnv(registry: string, tmpRc: string) {
  const host = registry.replace(/^https?:/, '');
  writeFileSync(tmpRc, `registry=${registry}\n${host}:_authToken=factory-local\n`);
  return { ...process.env, npm_config_userconfig: tmpRc, NPM_CONFIG_USERCONFIG: tmpRc };
}

function isPublished(pkg: ReleasePackage, version: string, env: NodeJS.ProcessEnv, registry: string): boolean {
  try {
    execFileSync('npm', ['view', `${pkg.name}@${version}`, 'version', '--registry', registry], { env, stdio: 'pipe' });
    return true;
  } catch {
    return false;
  }
}

export function release(material: string, opts: { root?: string; registry?: string; store?: string; signingKey?: string } = {}): string[] {
  const root = opts.root ?? '.';
  const signingKey = opts.signingKey ?? process.env['FACTORY_SIGNING_KEY'];
  if (!signingKey) throw new Error('FACTORY_SIGNING_KEY (PEM, ECDSA P-256 PKCS#8) is required: every release is signed');
  const store = resolve(root, opts.store ?? process.env['FACTORY_ATTESTATION_STORE'] ?? join('dist', 'attestations'));
  const registry = opts.registry ?? process.env['FACTORY_REGISTRY'] ?? DEFAULT_REGISTRY;
  const pkgs = packagesFor(material, root);
  if (pendingChangesets(root)) {
    execFileSync('pnpm', ['changeset', 'version'], { cwd: root, stdio: 'inherit' });
  }
  const rc = resolve(root, 'dist', 'release.npmrc');
  mkdirSync(join(root, 'dist'), { recursive: true });
  const env = npmEnv(registry, rc);
  const published: string[] = [];
  for (const pkg of pkgs) {
    stage(pkg);
    const version = readVersion(pkg);
    if (isPublished(pkg, version, env, registry)) {
      console.log(`${pkg.name}@${version}: already published, skipping`);
      continue;
    }
    execFileSync('npm', ['publish', '--registry', registry, '--access', 'restricted'], { cwd: pkg.dir, env, stdio: 'inherit' });
    const a = attest(pkg.dir, store, signingKey);
    const prov = writeProvenance(
      provenanceFor({
        tarball: { name: basename(a.tarball), bytes: readFileSync(a.tarball) },
        pkgDir: pkg.dir,
        material: { name: material, version },
        emitters: [emitterRef(pkg.emitter, root)],
        commit: gitCommit(root),
      }),
      a.tarball,
      signingKey,
    );
    console.log(`${pkg.name}@${version}: wrote ${a.sbom}, ${a.sig} and ${prov.statement}`);
    published.push(`${pkg.name}@${version}`);
  }
  return published;
}
