import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { parse } from 'yaml';

export const emitterId = 'nest-server';
export const emitterVersion = '1.0.0';

/** Shared contract types (docs/architecture.md, "Plugin contracts"). */
export type MaterialType = 'api-contract';

export interface MaterialBundle {
  name: string;
  type: MaterialType;
  /** OpenAPI 3 document (absolute path). */
  specPath: string;
}

export interface EmitOptions {
  /** Directory the server code is written to (absolute path). Replaced on every run. */
  outputDir: string;
}

export interface EmittedPackage {
  emitter: { id: string; version: string };
  outputDir: string;
  /** Files relative to `outputDir`, sorted. */
  files: string[];
}

/** Emitter contract: `accepts` api-contract materials, `target` nestjs. */
export const emitter: {
  id: string;
  version: string;
  accepts: MaterialType[];
  target: 'nestjs';
  emit(input: MaterialBundle, opts: EmitOptions): Promise<EmittedPackage>;
} = {
  id: emitterId,
  version: emitterVersion,
  accepts: ['api-contract'],
  target: 'nestjs' as const,
  emit,
};

/* eslint-disable @typescript-eslint/no-explicit-any */
type Schema = any;

const HEADER = '// Generated by nest-server. Do not edit.\n';
const HTTP = ['get', 'post', 'put', 'patch', 'delete'] as const;

const pascal = (s: string) => s.replace(/(^|[^A-Za-z0-9]+)([A-Za-z0-9])/g, (_, __, c: string) => c.toUpperCase());
const camel = (s: string) => {
  const p = pascal(s);
  return p.charAt(0).toLowerCase() + p.slice(1);
};
const kebab = (s: string) =>
  s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[^A-Za-z0-9]+/g, '-').toLowerCase();
const IDENT = /^[A-Za-z_$][\w$]*$/;

/** Spec-derived names become class, const and member names: refuse anything that is not a plain identifier. */
function ident(name: unknown, what: string): string {
  if (typeof name !== 'string' || !IDENT.test(name)) {
    throw new Error(`nest-server: ${what} ${JSON.stringify(name)} is not a valid identifier`);
  }
  return name;
}

/** Numeric constraints are emitted as code: require a finite number. */
function num(value: unknown, what: string): number {
  const n = typeof value === 'string' && value.trim() === '' ? NaN : Number(value);
  if (!Number.isFinite(n)) throw new Error(`nest-server: ${what} ${JSON.stringify(value)} is not a finite number`);
  return n;
}

/** Text for a block comment; it cannot close the comment early. */
const docText = (v: unknown) => String(v).replace(/\*\//g, '* /');

/** Single-quoted string literal. */
const quote = (v: string) =>
  `'${JSON.stringify(v).slice(1, -1).replace(/\\"/g, '"').replace(/'/g, "\\'")}'`;

const refName = (ref: string) => ident(ref.split('/').pop(), 'schema name');

/** Resolve `allOf: [$ref]` wrappers that TypeSpec emits to add a description to a reference. */
function unwrap(s: Schema): Schema {
  if (s?.allOf?.length === 1) return s.allOf[0];
  return s;
}

interface Prop {
  ts: string;
  decorators: Set<string>;
  imports: Set<string>; // class-validator names
  dtos: Set<string>; // referenced dto classes
}

function typeOf(raw: Schema, p: Prop, enums: Map<string, string[]>): void {
  const s = unwrap(raw);
  if (s.$ref) {
    const name = refName(s.$ref);
    const values = enums.get(name);
    if (values) {
      p.ts = name;
      p.imports.add('IsIn');
      p.decorators.add(`@IsIn(${name}Values)`);
      p.dtos.add(name);
    } else {
      p.ts = `${name}Dto`;
      p.imports.add('ValidateNested');
      p.decorators.add('@ValidateNested()');
      p.decorators.add(`@Type(() => ${name}Dto)`);
      p.dtos.add(name);
    }
    return;
  }
  if (s.enum) {
    p.ts = s.enum.map((v: string) => JSON.stringify(v)).join(' | ');
    p.imports.add('IsIn');
    p.decorators.add(`@IsIn(${JSON.stringify(s.enum)})`);
    return;
  }
  switch (s.type) {
    case 'string': {
      p.ts = 'string';
      p.imports.add('IsString');
      p.decorators.add('@IsString()');
      if (s.format === 'date-time') {
        p.imports.add('IsISO8601');
        p.decorators.add('@IsISO8601()');
      }
      if (s.minLength !== undefined) {
        p.imports.add('MinLength');
        p.decorators.add(`@MinLength(${num(s.minLength, 'minLength')})`);
      }
      if (s.maxLength !== undefined) {
        p.imports.add('MaxLength');
        p.decorators.add(`@MaxLength(${num(s.maxLength, 'maxLength')})`);
      }
      if (s.pattern !== undefined) {
        try {
          new RegExp(s.pattern);
        } catch {
          throw new Error(`nest-server: pattern ${JSON.stringify(s.pattern)} is not a valid regular expression`);
        }
        p.imports.add('Matches');
        p.decorators.add(`@Matches(new RegExp(${JSON.stringify(s.pattern)}))`);
      }
      return;
    }
    case 'integer':
    case 'number': {
      p.ts = 'number';
      p.imports.add(s.type === 'integer' ? 'IsInt' : 'IsNumber');
      p.decorators.add(s.type === 'integer' ? '@IsInt()' : '@IsNumber()');
      if (s.minimum !== undefined) {
        p.imports.add('Min');
        p.decorators.add(`@Min(${num(s.minimum, 'minimum')})`);
      }
      if (s.maximum !== undefined) {
        p.imports.add('Max');
        p.decorators.add(`@Max(${num(s.maximum, 'maximum')})`);
      }
      return;
    }
    case 'boolean':
      p.ts = 'boolean';
      p.imports.add('IsBoolean');
      p.decorators.add('@IsBoolean()');
      return;
    case 'array': {
      const inner: Prop = { ts: 'unknown', decorators: new Set(), imports: new Set(), dtos: new Set() };
      typeOf(s.items ?? {}, inner, enums);
      p.ts = inner.ts.includes(' | ') ? `(${inner.ts})[]` : `${inner.ts}[]`;
      p.imports.add('IsArray');
      p.decorators.add('@IsArray()');
      if (s.minItems !== undefined) {
        p.imports.add('ArrayMinSize');
        p.decorators.add(`@ArrayMinSize(${num(s.minItems, 'minItems')})`);
      }
      if (s.maxItems !== undefined) {
        p.imports.add('ArrayMaxSize');
        p.decorators.add(`@ArrayMaxSize(${num(s.maxItems, 'maxItems')})`);
      }
      // Element-level checks: nested DTOs validate each item.
      if (inner.dtos.size && inner.ts.endsWith('Dto')) {
        p.imports.add('ValidateNested');
        p.decorators.add('@ValidateNested({ each: true })');
        p.decorators.add(`@Type(() => ${inner.ts})`);
      } else if (inner.decorators.size) {
        for (const d of inner.decorators) {
          const withEach = d.endsWith('()') ? d.replace(/\(\)$/, '({ each: true })') : null;
          if (withEach && !d.startsWith('@ValidateNested')) {
            // Only no-argument decorators take `{ each: true }` as their sole option.
            p.decorators.add(withEach);
          }
        }
        for (const i of inner.imports) p.imports.add(i);
      }
      for (const d of inner.dtos) p.dtos.add(d);
      return;
    }
    default:
      p.ts = 'unknown';
  }
}

function renderProp(name: string, raw: Schema, required: boolean, enums: Map<string, string[]>) {
  const p: Prop = { ts: 'unknown', decorators: new Set(), imports: new Set(), dtos: new Set() };
  typeOf(raw, p, enums);
  const s = unwrap(raw);
  // Server-assigned fields are not validated on input.
  const optional = !required || raw.readOnly === true || s.readOnly === true;
  if (optional) {
    p.imports.add('IsOptional');
  }
  const lines: string[] = [];
  const doc = raw.description ?? s.description;
  if (doc) lines.push(`  /** ${docText(doc)} */`);
  if (optional) lines.push('  @IsOptional()');
  for (const d of [...p.decorators].sort()) lines.push(`  ${d}`);
  lines.push(`  ${ident(name, 'property name')}${optional ? '?' : '!'}: ${p.ts};`);
  return { text: lines.join('\n'), p };
}

function renderDto(name: string, schema: Schema, enums: Map<string, string[]>): string {
  const required = new Set<string>(schema.required ?? []);
  const imports = new Set<string>();
  const refs = new Set<string>();
  const props: string[] = [];
  let usesType = false;
  for (const key of Object.keys(schema.properties ?? {})) {
    const { text, p } = renderProp(key, schema.properties[key], required.has(key), enums);
    props.push(text);
    for (const i of p.imports) imports.add(i);
    for (const d of p.dtos) if (d !== name) refs.add(d);
    if (text.includes('@Type(')) usesType = true;
  }
  ident(name, 'schema name');
  const out: string[] = [HEADER];
  if (imports.size) out.push(`import { ${[...imports].sort().join(', ')} } from 'class-validator';`);
  if (usesType) out.push(`import { Type } from 'class-transformer';`);
  for (const r of [...refs].sort()) {
    out.push(
      enums.has(r)
        ? `import { ${r}, ${r}Values } from './${kebab(r)}.js';`
        : `import { ${r}Dto } from './${kebab(r)}.dto.js';`,
    );
  }
  out.push('');
  if (schema.description) out.push(`/** ${docText(schema.description)} */`);
  out.push(`export class ${name}Dto {`, props.join('\n\n'), '}', '');
  return out.join('\n');
}

function renderEnum(name: string, schema: Schema): string {
  ident(name, 'enum name');
  const values = schema.enum.map((v: string) => JSON.stringify(v)).join(', ');
  const doc = schema.description ? `/** ${docText(schema.description)} */\n` : '';
  return `${HEADER}\n${doc}export const ${name}Values = [${values}] as const;\nexport type ${name} = (typeof ${name}Values)[number];\n`;
}

interface Operation {
  id: string;
  method: (typeof HTTP)[number];
  path: string;
  doc?: string;
  params: { name: string; in: 'path' | 'query'; required: boolean; schema: Schema; description?: string }[];
  body?: string;
  responseType: string;
  successStatus: number;
  dtos: Set<string>;
}

function responseTypeOf(op: any, enums: Map<string, string[]>): { ts: string; status: number; dtos: Set<string> } {
  const ok = Object.keys(op.responses ?? {})
    .filter((c) => /^2\d\d$/.test(c))
    .sort()[0];
  const schema = ok ? op.responses[ok]?.content?.['application/json']?.schema : undefined;
  const dtos = new Set<string>();
  if (!schema) return { ts: 'void', status: ok ? Number(ok) : 204, dtos };
  const p: Prop = { ts: 'unknown', decorators: new Set(), imports: new Set(), dtos };
  typeOf(schema, p, enums);
  return { ts: p.ts, status: Number(ok), dtos };
}

async function listFiles(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true });
  return entries
    .filter((e) => e.isFile())
    .map((e) => relative(dir, join(e.parentPath, e.name)).split('\\').join('/'))
    .sort();
}

function renderController(tag: string, ops: Operation[], enums: Map<string, string[]>): string {
  const cls = `${pascal(tag)}ControllerBase`;
  const nest = new Set(['Body', 'HttpCode', 'Param', 'Query']);
  const dtoImports = new Set<string>();
  const queryClasses: string[] = [];
  const methods: string[] = [];
  const used = new Set<string>();
  for (const op of ops) {
    const verb = pascal(op.method);
    used.add(verb);
    const args: string[] = [];
    const callArgs: string[] = [];
    for (const prm of op.params.filter((x) => x.in === 'path')) {
      const p: Prop = { ts: 'unknown', decorators: new Set(), imports: new Set(), dtos: new Set() };
      typeOf(prm.schema, p, enums);
      args.push(`@Param(${quote(prm.name)}) ${ident(prm.name, 'path parameter name')}: ${p.ts}`);
      callArgs.push(prm.name);
    }
    const query = op.params.filter((x) => x.in === 'query');
    if (query.length) {
      const qName = `${pascal(ident(op.id, 'operationId'))}Query`;
      args.push(`@Query() query: ${qName}`);
      callArgs.push('query');
      queryClasses.push(renderQueryClass(qName, query, enums));
    }
    if (op.body) {
      args.push(`@Body() body: ${op.body}Dto`);
      callArgs.push('body');
      dtoImports.add(`${op.body}Dto`);
    }
    for (const d of op.dtos) dtoImports.add(enums.has(d) ? d : `${d}Dto`);
    const ret = op.responseType === 'void' ? 'void' : op.responseType;
    const retDto = ret.replace(/\[\]$/, '');
    if (/Dto$/.test(retDto)) dtoImports.add(retDto);
    const path = op.path.replace(/\{(\w+)\}/g, ':$1');
    if (op.doc) methods.push(`  /** ${docText(op.doc)} */`);
    methods.push(
      `  @${verb}(${quote(path)})`,
      `  @HttpCode(${op.successStatus})`,
      `  ${camel(op.id)}Route(${args.join(', ')}): Promise<${ret}> | ${ret} {`,
      `    return this.${camel(op.id)}(${callArgs.join(', ')});`,
      '  }',
      '',
      `  /** Implement ${op.method.toUpperCase()} ${op.path}. */`,
      `  abstract ${camel(op.id)}(${args.map((a) => a.replace(/^@\w+\([^)]*\) /, '')).join(', ')}): Promise<${ret}> | ${ret};`,
      '',
    );
  }
  const validators = new Set<string>();
  for (const q of queryClasses) for (const m of q.matchAll(/@(\w+)\(/g)) if (m[1] !== 'Type') validators.add(m[1]!);
  const out: string[] = [HEADER];
  out.push(`import { ${[...nest, ...used].sort().join(', ')} } from '@nestjs/common';`);
  if (queryClasses.length) {
    out.push(`import { Type } from 'class-transformer';`);
    out.push(`import { ${[...validators].sort().join(', ')} } from 'class-validator';`);
  }
  for (const d of [...dtoImports].sort()) {
    const base = d.replace(/Dto$/, '');
    out.push(
      enums.has(d)
        ? `import type { ${d} } from '../dto/${kebab(d)}.js';`
        : `import { ${d} } from '../dto/${kebab(base)}.dto.js';`,
    );
  }
  out.push('');
  for (const q of queryClasses) out.push(q, '');
  out.push(`/** Abstract controller for the \`${tag}\` tag. Extend it, add \`@Controller()\`, implement the operations. */`);
  out.push(`export abstract class ${cls} {`, methods.join('\n').replace(/\n+$/, ''), '}', '');
  return out.join('\n');
}

function renderQueryClass(name: string, params: Operation['params'], enums: Map<string, string[]>): string {
  const lines: string[] = [`export class ${name} {`];
  const body: string[] = [];
  for (const prm of params) {
    const p: Prop = { ts: 'unknown', decorators: new Set(), imports: new Set(), dtos: new Set() };
    typeOf(prm.schema, p, enums);
    const parts: string[] = [];
    if (prm.description) parts.push(`  /** ${docText(prm.description)} */`);
    if (!prm.required) parts.push('  @IsOptional()');
    if (p.ts === 'number') parts.push('  @Type(() => Number)');
    for (const d of [...p.decorators].sort()) parts.push(`  ${d}`);
    parts.push(`  ${ident(prm.name, 'query parameter name')}${prm.required ? '!' : '?'}: ${p.ts};`);
    body.push(parts.join('\n'));
  }
  lines.push(body.join('\n\n'), '}');
  return lines.join('\n');
}

export async function emit(bundle: MaterialBundle, opts: EmitOptions): Promise<EmittedPackage> {
  const doc: any = parse(await readFile(resolve(bundle.specPath), 'utf8'));
  const schemas: Record<string, Schema> = doc.components?.schemas ?? {};
  const enums = new Map<string, string[]>();
  for (const [n, s] of Object.entries(schemas)) if (s.enum) enums.set(n, s.enum);

  const files = new Map<string, string>();
  for (const name of Object.keys(schemas).sort()) {
    const s = schemas[name];
    if (s.enum) files.set(`dto/${kebab(name)}.ts`, renderEnum(name, s));
    else if (s.type === 'object') files.set(`dto/${kebab(name)}.dto.ts`, renderDto(name, s, enums));
  }

  const byTag = new Map<string, Operation[]>();
  for (const path of Object.keys(doc.paths ?? {}).sort()) {
    for (const method of HTTP) {
      const op = doc.paths[path][method];
      if (!op) continue;
      const rt = responseTypeOf(op, enums);
      const bodySchema = op.requestBody?.content?.['application/json']?.schema;
      const operation: Operation = {
        id: op.operationId ?? camel(`${method}-${path}`),
        method,
        path,
        doc: op.description ?? op.summary,
        params: [...(doc.paths[path].parameters ?? []), ...(op.parameters ?? [])].map((x: any) => ({
          name: x.name,
          in: x.in,
          required: x.required === true,
          schema: x.schema ?? {},
          description: x.description,
        })),
        body: bodySchema?.$ref ? refName(bodySchema.$ref) : undefined,
        responseType: rt.ts,
        successStatus: rt.status,
        dtos: rt.dtos,
      };
      const tag = op.tags?.[0] ?? 'Default';
      byTag.set(tag, [...(byTag.get(tag) ?? []), operation]);
    }
  }
  for (const [tag, ops] of [...byTag].sort(([a], [b]) => a.localeCompare(b))) {
    files.set(`controllers/${kebab(tag)}.controller.base.ts`, renderController(tag, ops, enums));
  }
  const barrel = [...files.keys()].sort().map((f) => `export * from './${f.replace(/\.ts$/, '.js')}';`);
  files.set('index.ts', `${HEADER}${barrel.join('\n')}\n`);

  const output = resolve(opts.outputDir);
  await rm(output, { recursive: true, force: true });
  for (const [f, text] of files) {
    await mkdir(dirname(join(output, f)), { recursive: true });
    await writeFile(join(output, f), text);
  }
  return { emitter: { id: emitterId, version: emitterVersion }, outputDir: output, files: await listFiles(output) };
}
